import assert from 'node:assert/strict';
import fs from 'node:fs';
import { AVATARS, avatarIdPattern, normalizeAvatarId, avatarImageUrl } from '../js/avatars.js';
import { makeRulesV3 } from '../js/rules-v3.js';
import { gradeAnswer, totalScores, buildRoundReport, ranking } from '../js/classic-core.js';
const read = path => fs.readFileSync(new URL('../'+path,import.meta.url),'utf8');
assert.equal(AVATARS.length,20);
assert.equal(new Set(AVATARS.map(a=>a.id)).size,20);
for(const avatar of AVATARS){
 assert.match(avatar.id,avatarIdPattern);
 assert.ok(avatar.name.length>=2);
 assert.match(avatarImageUrl(avatar.id),new RegExp('images/avatars/'+avatar.id+'\\.png'));
 assert.ok(fs.existsSync(new URL('../images/avatars/'+avatar.id+'.png',import.meta.url)));
}
assert.equal(normalizeAvatarId('a20'),'a20');
assert.equal(normalizeAvatarId('../../secret'),'a01');
assert.equal(normalizeAvatarId(123),'a01');
const rules=JSON.parse(makeRulesV3('teacherUid123456'));
const profile=rules.rules.v2.rooms['$code'].members['$uid'].profile;
assert.match(profile.avatarId['.validate'],/matches\(/);
assert.equal(profile['$other']['.validate'],false);
assert.match(profile['.write'],/auth\.uid === \$uid/);
assert.match(profile['.write'],/nameClaims/);
assert.ok(rules.rules.v3.answers && rules.rules.v3.privateRuns && rules.rules.v1);
const score=totalScores({q1:{student1:{points:788,correct:true,responseMs:4000}}},{student1:{profile:{name:'테스트',avatarId:'a18'}}});
assert.equal(score.student1.avatarId,'a18');
assert.equal(score.student1.score,788);
const report=buildRoundReport('q1',{student1:{points:788,correct:true,responseMs:4000}},{student1:{value:'1'}},{student1:'테스트'},score);
assert.equal(report.entries.student1.avatarId,'a18');
assert.equal(report.entries.student1.points,788);
assert.equal(ranking(score)[0].avatarId,'a18');
const grade=gradeAnswer({type:'multiple',correctIndex:1,timeLimit:30,options:['A','B','C','D']},'1',104000,100000,130000);
assert.equal(grade.correct,true);assert.equal(grade.points,933);
const lobby=read('join.html'),host=read('rooms.html'),js=read('js/join.js');
for(const id of ['avatar-self','avatar-current','avatar-choose','avatar-dialog','avatar-grid','avatar-feedback'])assert.match(lobby,new RegExp('id="'+id+'"'));
assert.match(lobby,/avatars\.css\?v=3\.8/);
assert.match(host,/avatar-copy-rules/);
assert.match(js,/avatarId:id/);
assert.match(js,/update\(ref\(db,`v2\/rooms\/\$\{requestedCode\}\/members\/\$\{requestedUid\}\/profile`\)/);
assert.match(read('js/classic-student.js'),/createAvatarImage\(/);
assert.match(read('js/arcade-ui.js'),/createAvatarImage\(/);
console.log('v3.8 20 avatars, auth-limited profile write, leaderboard/podium, score preserved: PASS');
