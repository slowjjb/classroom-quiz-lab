const base='https://slowjjb.github.io/classroom-quiz-lab/';
const fetched=[];
const fetchImpl=async (url, opts)=>{
  assert.equal(opts.method,'HEAD'); fetched.push(url);
  if(url.includes('not-found'))return {status:404,ok:false,headers:{get:()=>''}};
  if(url.includes('fake'))return {status:200,ok:true,headers:{get:()=> 'text/html; charset=UTF-8'}};
  if(url.includes('forbidden'))return {status:403,ok:false,headers:{get:()=>''}};
  if(url.includes('offline'))throw new Error('NetworkError');
  return {status:200,ok:true,headers:{get:()=> 'image/png'}};
};
