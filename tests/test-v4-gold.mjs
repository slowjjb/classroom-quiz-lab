import assert from 'node:assert/strict';
import fs from 'node:fs';
import {makeShuffleBag,verifyGoldAnswer,chooseGoldOutcome,applyGoldOutcome,goldRanking} from '../js/gold-core.js';
import {makeRulesV4} from '../js/rules-v4.js';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
// Shufflebag: all questions appear once per 20, no repeats in the recent 10.
const bag=makeShuffleBag(20,100,()=>.37);
assert.equal(bag.length,100);
for(let n=0;n<bag.length;n++)assert.ok(!bag.slice(Math.max(0,n-10),n).includes(bag[n]),`repeat within 10 at ${n}`);
for(let block=0;block<5;block++)assert.equal(new Set(bag.slice(block*20,block*20+20)).size,20);
const tiny=makeShuffleBag(1,5,()=>.1);assert.deepEqual(tiny,[0,0,0,0,0]);
assert.ok(verifyGoldAnswer({type:'typing',options:['물','H2O','']},'  h2o  '));
assert.ok(verifyGoldAnswer({type:'multiple_choice',options:['A','B','C','D'],correctIndex:3},'3'));
assert.ok(!verifyGoldAnswer({type:'multiple_choice',options:['A','B','C','D'],correctIndex:3},'4'));
assert.equal(chooseGoldOutcome(()=>.63).type,'bonus');
assert.equal(chooseGoldOutcome(()=>.8,{allowInteractions:true,playerCount:2}).type,'steal');
assert.equal(chooseGoldOutcome(()=>.9,{allowInteractions:true,playerCount:2}).type,'swap');
assert.equal(chooseGoldOutcome(()=>.9,{allowInteractions:false,playerCount:2}).type,'jackpot');
let scores={a:{name:'A',gold:50},b:{name:'B',gold:300}};
const stolen=applyGoldOutcome(scores,'a',{type:'steal',amount:100},'b');
assert.equal(stolen.scores.a.gold,150);assert.equal(stolen.scores.b.gold,200);
assert.equal(scores.a.gold,50,'function must not mutate input');
const exchanged=applyGoldOutcome(scores,'a',{type:'swap',portion:.2},'b');
assert.equal(exchanged.scores.a.gold,100);assert.equal(exchanged.scores.b.gold,250);
assert.equal(goldRanking(stolen.scores)[0].uid,'b');
const rules=JSON.parse(makeRulesV4('teacherUid123456'));
assert.ok(rules.rules.v1&&rules.rules.v2&&rules.rules.v3&&rules.rules.v4);
assert.match(rules.rules.v4.privateRuns['$code']['.read'],/google.com/);
assert.match(rules.rules.v4.memberState['$code']['$uid']['.read'],/auth.uid === \$uid/);
assert.match(rules.rules.v4.memberState['$code']['.read'],/google.com/);
assert.match(rules.rules.v4.answers['$code']['$uid']['$nonce']['.write'],/!data.exists\(\)/);
assert.match(rules.rules.v4.picks['$code']['$uid']['$nonce']['.write'],/phase/);
assert.equal(rules.rules.v2.rooms['$code'].members['$uid'].profile['$other']['.validate'],false);
const host=read('js/gold-host.js'),student=read('js/gold-student.js');
assert.match(host,/privateRuns/);assert.match(host,/verifyGoldAnswer/);assert.match(host,/applyGoldOutcome/);
assert.match(student,/serverTimestamp\(\)/);assert.ok(!student.includes('correctIndex'), 'student code must not use private answers');
for(const name of ['gold-panel','gold-prepare','gold-start','gold-end','gold-live-ranking','gold-focus','gold-copy-rules'])assert.ok(read('rooms.html').includes(`id="${name}"`),name);
for(const name of ['gold-student','gold-submit','gold-answer-choices','gold-chest-buttons','gold-student-clock'])assert.ok(read('join.html').includes(`id="${name}"`),name);
console.log('v4 shufflebag, answer grading, steal/swap, rules, mode UI: PASS');
